package builder

import (
	"context"
	"fmt"
	"path/filepath"
	"strings"

	"github.com/bright-interaction/slab/internal/store"
)

// RenderCSS generates the global.css file from site branding and CSS classes.
func RenderCSS(ctx context.Context, queries *store.Queries, siteID string, wsDir string) error {
	site, err := queries.GetSiteByID(ctx, siteID)
	if err != nil {
		return fmt.Errorf("get site: %w", err)
	}

	classes, err := queries.ListCSSClassesBySite(ctx, siteID)
	if err != nil {
		return fmt.Errorf("list css classes: %w", err)
	}

	var b strings.Builder

	// CSS custom properties from branding
	b.WriteString("/* Auto-generated by Atomicsite */\n\n")
	b.WriteString(":root {\n")
	b.WriteString(fmt.Sprintf("  --color-primary: %s;\n", site.PrimaryColor))
	b.WriteString(fmt.Sprintf("  --color-secondary: %s;\n", site.SecondaryColor))
	b.WriteString(fmt.Sprintf("  --color-bg: %s;\n", site.BgColor))
	b.WriteString(fmt.Sprintf("  --color-text: %s;\n", site.TextColor))
	b.WriteString(fmt.Sprintf("  --font-heading: '%s', system-ui, sans-serif;\n", site.FontHeading))
	b.WriteString(fmt.Sprintf("  --font-body: '%s', system-ui, sans-serif;\n", site.FontBody))
	b.WriteString("}\n\n")

	// Reset
	b.WriteString("*, *::before, *::after { box-sizing: border-box; margin: 0; }\n")
	b.WriteString("html { font-family: var(--font-body); color: var(--color-text); background-color: var(--color-bg); line-height: 1.6; }\n")
	b.WriteString("body { min-height: 100dvh; }\n")
	b.WriteString("h1, h2, h3, h4, h5, h6 { font-family: var(--font-heading); line-height: 1.2; }\n")
	b.WriteString("a { color: var(--color-primary); }\n")
	b.WriteString("img { max-width: 100%; height: auto; display: block; }\n\n")

	// User-defined CSS classes
	if len(classes) > 0 {
		b.WriteString("/* --- Site CSS Classes --- */\n\n")
		currentCategory := ""
		for _, cc := range classes {
			if cc.Category != currentCategory {
				currentCategory = cc.Category
				b.WriteString(fmt.Sprintf("/* %s */\n", currentCategory))
			}
			if cc.UsageNote != "" {
				b.WriteString(fmt.Sprintf("/* %s */\n", cc.UsageNote))
			}
			b.WriteString(cc.Css)
			b.WriteString("\n\n")
		}
	}

	return WriteFile(filepath.Join(wsDir, "src", "styles", "global.css"), b.String())
}
